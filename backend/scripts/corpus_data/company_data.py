def build_chapters(custom: list[tuple[str, list[str]]] | None = None) -> list[tuple[str, list[str]]]:
    """按模板生成章节内容；custom 可覆盖特定章节（按章名匹配，缺省用模板）。"""
    chapters = []
    for name, items in TEMPLATE_CHAPTERS.items():
        if custom:
            for cname, citems in custom:
                if cname == name:
                    items = citems
                    break
        chapters.append((name, items))
    return chapters


